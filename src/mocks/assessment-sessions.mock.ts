function rec(input: Partial<OccupationRecommendation> & { occupationId: string; occupationName: string; totalScore: number; readinessScore: number }): OccupationRecommendation {
  const totalScore = input.totalScore;
  const grade: OccupationRecommendation["grade"] =
    totalScore >= 85 ? "매우 잘 맞아요" : totalScore >= 70 ? "잘 맞아요" : totalScore >= 55 ? "도전해볼 만해요" : "준비가 더 필요해요";
  return {
    occupationCategory: undefined,
    jobCategoryCode: undefined,
    dimensionFitScore: input.dimensionFitScore ?? totalScore,
    conditionFitScore: input.conditionFitScore ?? totalScore - 5,
    entryFeasibilityScore: input.entryFeasibilityScore ?? totalScore - 10,
    experienceUtilizationScore: input.experienceUtilizationScore ?? totalScore - 8,
    reasons: input.reasons ?? [],
    risks: input.risks ?? [],
    missingConditions: input.missingConditions ?? [],
    requiredQualifications: input.requiredQualifications ?? [],
    recommendedContentIds: input.recommendedContentIds ?? [],
    readinessProjection: input.readinessProjection ?? [],
    grade,
    ...input,
  };
}

