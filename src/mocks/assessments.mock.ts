const ASSESSMENT_ID = "assessment-career-v1";

function q(
  partial: Omit<AssessmentQuestion, "assessmentId" | "options"> & {
    options?: Omit<AssessmentOption, "questionId">[];
  },
): AssessmentQuestion {
  return {
    ...partial,
    assessmentId: ASSESSMENT_ID,
    options: partial.options?.map((o) => ({ ...o, questionId: partial.id })),
  };
}

